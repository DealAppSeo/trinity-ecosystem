const { createClient } = require('@supabase/supabase-js');
require('dotenv').config();

const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

async function createBidsTable() {
    console.log('--- CREATING COMPUTE_BIDS TABLE ---');

    const sql = `
        CREATE TABLE IF NOT EXISTS public.compute_bids (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            agent_id TEXT NOT NULL,
            task_id BIGINT,
            bid_type TEXT NOT NULL, -- LOCAL, CLOUD, P2P
            provider TEXT, -- Ollama, OpenAI, Vast.AI, etc.
            cost_estimate FLOAT DEFAULT 0.0,
            latency_estimate_ms INT,
            accuracy_score FLOAT,
            is_winner BOOLEAN DEFAULT false,
            stewardship_weight FLOAT,
            decided_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
        );

        CREATE INDEX IF NOT EXISTS idx_compute_bids_agent_id ON public.compute_bids(agent_id);
    `;

    // The parameter is named 'query' in update_exec_sql_v2.sql
    const { error } = await supabase.rpc('exec_sql', { query: sql });

    if (error) {
        console.error('Table creation failed:', error.message);
    } else {
        console.log('compute_bids table ready.');
    }
}

createBidsTable();

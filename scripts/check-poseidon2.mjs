#!/usr/bin/env node
// scripts/check-poseidon2.mjs — does our Poseidon2 agree with Plonky3's?
//
// THE ONLY QUESTION THAT MATTERS HERE. A hash implementation is either
// bit-identical to the one the verifier uses or it is worthless, and the failure
// is silent: a wrong parameter set produces plausible field elements, passes its
// own round-trip tests, and disagrees with every other implementation on earth.
// Nothing notices until two systems compare a root in production, by which point
// both have persisted data under incompatible hashes.
//
// So this suite asserts NOTHING about internal consistency. It runs the known-
// answer vectors produced by Plonky3's own `default_babybear_poseidon2_16()` and
// compares outputs. A round-trip test would pass on a completely invented
// parameter set; a KAT cannot.
//
// PROVENANCE OF THE ORACLE. `lib/trustshell/identity/fixtures/*.json` are copied
// from repid-engine's `zkp-vault/kat/`, generated by the audited Rust
// implementation. That harness is itself proven to call p3 correctly — it
// reproduces p3-poseidon2 0.3.0's OWN published width-16 test vector — so
// matching it is cross-language parity, not "both wrong the same way".
//
// WHAT A PASS HERE DOES NOT MEAN. It does not mean `IBindingScheme` is
// implemented. The permutation is determined; the encoding from
// `commit(secret: string)` to field elements, and the domain-tag encoding, are
// not, and no vector here speaks to them. See docs/POSEIDON2-PARAMETER-REQUEST.md.
//
// THREE OUTCOMES. VERIFIED / NOT CHECKED / FAILED. A missing fixture or a failed
// compile is NOT CHECKED, never a pass.

import { readFileSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { localTsc } from './local-tsc.mjs';

const FIXTURES = 'lib/trustshell/identity/fixtures';
const results = [];
const record = (state, control, detail) => results.push({ state, control, detail });

function report() {
  const width = Math.max(...results.map((r) => r.control.length));
  console.log('\nPoseidon2/BabyBear — parity with the Plonky3 oracle\n');
  for (const r of results) {
    const mark = r.state === 'VERIFIED' ? '✓' : r.state === 'FAILED' ? '✗' : '·';
    console.log(`  ${mark} ${r.control.padEnd(width)}  ${r.state}`);
    console.log(`    ${r.detail}`);
  }
  const failed = results.filter((r) => r.state === 'FAILED').length;
  const unchecked = results.filter((r) => r.state === 'NOT CHECKED').length;
  const verified = results.filter((r) => r.state === 'VERIFIED').length;
  console.log(`\ncheck:poseidon2 — ${verified} VERIFIED, ${unchecked} NOT CHECKED, ${failed} FAILED.`);
  process.exit(failed > 0 ? 1 : unchecked > 0 && verified === 0 ? 2 : 0);
}

// ---------------------------------------------------------------- load oracles
let rawKat, hash2Kat;
try {
  rawKat = JSON.parse(readFileSync(join(FIXTURES, 'poseidon2_babybear16_kat.json'), 'utf8'));
  hash2Kat = JSON.parse(readFileSync(join(FIXTURES, 'poseidon2_babybear16_2to1_kat.json'), 'utf8'));
} catch (err) {
  record('NOT CHECKED', 'read the oracle vectors', err.message);
  report();
}

// ---------------------------------------------------------------- compile
const out = mkdtempSync(join(process.cwd(), '.poseidon2-check-'));
let P;
try {
  const cfg = join(out, 'tsconfig.json');
  writeFileSync(
    cfg,
    JSON.stringify({
      compilerOptions: {
        outDir: out,
        rootDir: process.cwd(),
        module: 'commonjs',
        target: 'es2022',
        lib: ['es2022'],
        moduleResolution: 'node',
        esModuleInterop: true,
        strict: true,
        skipLibCheck: true,
      },
      files: [
        join(process.cwd(), 'lib/trustshell/identity/poseidon2-babybear.ts'),
        join(process.cwd(), 'lib/trustshell/identity/poseidon2-hash2.ts'),
      ],
    })
  );
  execFileSync(localTsc(), ['--project', cfg], { stdio: 'pipe' });
  P = {
    perm: await import(pathToFileURL(join(out, 'lib/trustshell/identity/poseidon2-babybear.js')).href),
    hash2: await import(pathToFileURL(join(out, 'lib/trustshell/identity/poseidon2-hash2.js')).href),
  };
} catch (err) {
  rmSync(out, { recursive: true, force: true });
  record(
    'NOT CHECKED',
    'compile the implementation',
    `${err.stdout?.toString() ?? ''}${err.stderr?.toString() ?? err.message}`
  );
  report();
}

// ---------------------------------------------------------------- field/shape
{
  const p = P.perm.BABYBEAR_P;
  const okField = p === BigInt(rawKat.field_prime);
  const okWidth = P.perm.POSEIDON2_WIDTH === rawKat.width;
  if (okField && okWidth) {
    record(
      'VERIFIED',
      'field and width match the oracle',
      `p = ${p} (2^31 - 2^27 + 1), width ${P.perm.POSEIDON2_WIDTH} — declared by the oracle, not by us`
    );
  } else {
    record(
      'FAILED',
      'field and width match the oracle',
      `ours p=${p} width=${P.perm.POSEIDON2_WIDTH}; oracle p=${rawKat.field_prime} width=${rawKat.width}`
    );
  }
}

// ---------------------------------------------------------------- raw permutation
{
  const bad = [];
  for (const v of rawKat.vectors) {
    let got;
    try {
      got = P.perm.poseidon2Permute16u32(v.input);
    } catch (e) {
      bad.push(`${v.name}: threw ${e.message}`);
      continue;
    }
    const want = v.output;
    if (got.length !== want.length || got.some((x, i) => x !== want[i])) {
      // Name the first differing lane: an off-by-one round shifts everything,
      // a bad constant usually moves one lane.
      const lane = got.findIndex((x, i) => x !== want[i]);
      bad.push(`${v.name}: first mismatch at lane ${lane} — got ${got[lane]}, want ${want[lane]}`);
    }
  }
  if (bad.length) {
    record(
      'FAILED',
      `raw permutation vs oracle (${rawKat.vectors.length} vectors)`,
      bad.join('\n    ') +
        '\n    A mismatch here means our permutation is a DIFFERENT FUNCTION from the verifier’s.' +
        '\n    Do not adjust the vectors to match the code.'
    );
  } else {
    record(
      'VERIFIED',
      `raw permutation vs oracle (${rawKat.vectors.length} vectors)`,
      `all ${rawKat.vectors.length} width-16 vectors reproduce p3 exactly, lane for lane`
    );
  }
}

// ---------------------------------------------------------------- 2-to-1 hash
{
  const bad = [];
  for (const v of hash2Kat.vectors) {
    let got;
    try {
      got = P.hash2.poseidon2Hash2u32(v.a, v.b);
    } catch (e) {
      bad.push(`${v.name}: threw ${e.message}`);
      continue;
    }
    if (got !== v.output) bad.push(`${v.name}: H(${v.a}, ${v.b}) = ${got}, oracle says ${v.output}`);
  }
  if (bad.length) {
    record('FAILED', `2-to-1 hash vs oracle (${hash2Kat.vectors.length} vectors)`, bad.join('\n    '));
  } else {
    record(
      'VERIFIED',
      `2-to-1 hash vs oracle (${hash2Kat.vectors.length} vectors)`,
      `H(a,b) = Perm16([a,b,0..])[0] reproduces the oracle on all ${hash2Kat.vectors.length} vectors`
    );
  }
}

// ---------------------------------------------------------------- canonicality
{
  // A hash that silently accepts a non-canonical input will disagree with the
  // circuit, which cannot represent one. Refusing is part of the contract.
  const rejects = [];
  const p = Number(P.perm.BABYBEAR_P);
  for (const [a, b, why] of [
    [p, 0, 'a == p'],
    [0, p, 'b == p'],
    [-1, 0, 'negative'],
    [1.5, 0, 'non-integer'],
  ]) {
    let threw = false;
    try {
      P.hash2.poseidon2Hash2u32(a, b);
    } catch {
      threw = true;
    }
    if (!threw) rejects.push(`accepted ${why}`);
  }
  if (rejects.length) {
    record('FAILED', 'non-canonical inputs are refused', rejects.join('; '));
  } else {
    record(
      'VERIFIED',
      'non-canonical inputs are refused',
      'values >= p, negative and non-integer inputs all throw rather than being reduced silently'
    );
  }
}

// ---------------------------------------------------------------- the caveat
{
  // Deliberately a control, not a comment: the thing most likely to go wrong now
  // is someone reading a green run here as "zk RepID has a working hash".
  const nullifier = readFileSync('lib/trustshell/identity/nullifier.ts', 'utf8');
  const stillRefuses = /class PendingPoseidon2Scheme[\s\S]*?throw new Error\(MISSING_PARAMETERS\)/.test(
    nullifier
  );
  if (stillRefuses) {
    record(
      'VERIFIED',
      'IBindingScheme still refuses, and says so',
      'the permutation is determined; the string→field and domain-tag encodings are NOT, ' +
        'so PendingPoseidon2Scheme still throws. Narrowing a blocker is not clearing it.'
    );
  } else {
    record(
      'NOT CHECKED',
      'IBindingScheme still refuses, and says so',
      'PendingPoseidon2Scheme no longer throws MISSING_PARAMETERS. If a real scheme landed, ' +
        'update this control to assert its KAT instead of deleting it.'
    );
  }
}

rmSync(out, { recursive: true, force: true });
report();

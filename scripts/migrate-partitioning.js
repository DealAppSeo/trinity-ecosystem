const { createClient } = require('@supabase/supabase-js');
require('dotenv').config();

const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);

async function partitionTable() {
    console.log('--- STARTING PARTITIONING ---');

    const sql = `
        -- 1. Drop old table
        DROP TABLE IF EXISTS public.agent_artifacts CASCADE;

        -- 2. Create partitioned table
        CREATE TABLE public.agent_artifacts (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY,
            agent_id TEXT NOT NULL,
            node_type TEXT NOT NULL,
            content TEXT,
            embedding vector(1536),
            sprint_id BIGINT NOT NULL,
            zk_weight FLOAT DEFAULT 1.0,
            content_hash TEXT,
            created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
            PRIMARY KEY (sprint_id, id)
        ) PARTITION BY LIST (sprint_id);

        -- 3. Create initial partition for sprint 0
        CREATE TABLE public.agent_artifacts_sprint_0 PARTITION OF public.agent_artifacts FOR VALUES IN (0);
        
        -- 4. Re-create indexes
        CREATE INDEX idx_agent_artifacts_content_hash ON public.agent_artifacts(content_hash);
        CREATE INDEX IF NOT EXISTS idx_agent_artifacts_agent_id ON public.agent_artifacts(agent_id);

        -- 5. HotStuff-2 Schema Alignment
        ALTER TABLE public.schema_change_proposals ADD COLUMN IF NOT EXISTS current_phase TEXT DEFAULT 'prepare';
        ALTER TABLE public.schema_change_proposals ADD COLUMN IF NOT EXISTS quorum_certificate JSONB;
    `;

    // The parameter is named 'query' in update_exec_sql_v2.sql
    const { error } = await supabase.rpc('exec_sql', { query: sql });

    if (error) {
        console.error('Partitioning failed:', error.message);
    } else {
        console.log('Partitioning complete.');
    }
}

partitionTable();
